"""Generate SQLAlchemy 2.x declarative models from a FROZEN schema map (deterministic)."""
from __future__ import annotations
from ..schema_map.schema_map import require_frozen
from ..generation.ddl import dependency_order, validate_identifier

def _singular(w):
    if w.endswith("ies"): return w[:-3] + "y"
    if w.endswith("s") and not w.endswith("ss"): return w[:-1]
    return w

def class_name(table: str) -> str:
    return "".join(p.capitalize() for p in (_singular(x) for x in table.split("_")))

def _sa_type(sql: str) -> str:
    b = sql.split("(")[0].upper()
    if b in ("TEXT",): return "Text"
    if b == "VARCHAR": return f"String({sql[sql.index('(') + 1:-1]})"
    if b in ("BIGINT", "BIGSERIAL"): return "BigInteger"
    if b == "INTEGER": return "Integer"
    if b == "DOUBLE PRECISION": return "Float"
    if b == "NUMERIC": return f"Numeric({sql[sql.index('(') + 1:-1]})"
    if b == "BOOLEAN": return "Boolean"
    if b == "TIMESTAMPTZ": return "DateTime(timezone=True)"
    raise ValueError(f"no SQLAlchemy type for {sql}")

def _py_type(sql: str) -> str:
    b = sql.split("(")[0].upper()
    return {"TEXT": "str", "VARCHAR": "str", "BIGINT": "int", "BIGSERIAL": "int", "INTEGER": "int",
            "DOUBLE PRECISION": "float", "NUMERIC": "Decimal", "BOOLEAN": "bool",
            "TIMESTAMPTZ": "datetime"}[b]

def generate_models(sm: dict, schema_name: str = "schemashift_demo") -> str:
    h = require_frozen(sm)
    validate_identifier(schema_name)
    tables = sm["tables"]
    order = dependency_order(tables)
    # relationship attribute names
    parent_attr = {}   # (table, fkcol) -> attribute on child
    child_attr = {}    # (ref_table, table, fkcol) -> attribute on parent
    for t in order:
        fks = tables[t]["foreign_keys"]
        for fk in fks:
            pa = fk["column"][:-3] if fk["column"].endswith("_id") else fk["column"] + "_ref"
            parent_attr[(t, fk["column"])] = pa
            same = [x for x in fks if x["ref_table"] == fk["ref_table"]]
            ca = t if len(same) == 1 and t != fk["ref_table"] else f"{t}_by_{fk['column']}"
            child_attr[(fk["ref_table"], t, fk["column"])] = ca
    L = [f'"""GENERATED by SchemaShift - DO NOT EDIT. Frozen map hash {h}, revision {sm["revision"]}.',
         'Regenerate with: python -m app.cli generate"""',
         "from __future__ import annotations", "from datetime import datetime", "from decimal import Decimal",
         "from typing import List, Optional",
         "from sqlalchemy import BigInteger, Boolean, DateTime, Float, ForeignKey, Integer, Numeric, String, Text, UniqueConstraint",
         "from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship", "",
         f'SCHEMA = "{schema_name}"', f'MAP_HASH = "{h}"', "",
         "class Base(DeclarativeBase):", "    pass", ""]
    for t in order:
        spec = tables[t]
        cn = class_name(t)
        L += ["", f"class {cn}(Base):", f'    __tablename__ = "{t}"']
        args = [f'UniqueConstraint({", ".join(repr(c) for c in u)})' for u in spec.get("unique", [])]
        args.append("{'schema': SCHEMA}")
        L.append(f"    __table_args__ = ({', '.join(args)},)")
        fkmap = {fk["column"]: fk for fk in spec["foreign_keys"]}
        for c in sorted(spec["columns"], key=lambda x: (x != "id", x)):
            validate_identifier(c)
            col = spec["columns"][c]
            ann = _py_type(col["sql_type"])
            opts = []
            sat = _sa_type(col["sql_type"])
            if c in fkmap:
                fk = fkmap[c]
                target = fk["ref_table"] + "." + fk["ref_column"]
                sat = sat + ', ForeignKey(f"{SCHEMA}.' + target + '")'
            if c in spec["primary_key"]:
                opts.append("primary_key=True")
                if col["sql_type"] == "BIGSERIAL": opts.append("autoincrement=True")
            elif col["nullable"]:
                opts.append("nullable=True")
            else:
                opts.append("nullable=False")
            ann = f"Optional[{ann}]" if col["nullable"] and c not in spec["primary_key"] else ann
            L.append(f"    {c}: Mapped[{ann}] = mapped_column({sat}, {', '.join(opts)})")
        for fk in spec["foreign_keys"]:
            ref_cn = class_name(fk["ref_table"])
            pa = parent_attr[(t, fk["column"])]
            ca = child_attr[(fk["ref_table"], t, fk["column"])]
            L.append(f'    {pa}: Mapped["{ref_cn}"] = relationship(back_populates="{ca}", foreign_keys=[{fk["column"]}])')
        for (ref, child, fkcol), attr in sorted(child_attr.items()):
            if ref == t:
                L.append(f'    {attr}: Mapped[List["{class_name(child)}"]] = relationship(back_populates="{parent_attr[(child, fkcol)]}", '
                         f'foreign_keys="{class_name(child)}.{fkcol}", cascade="save-update, merge")')
    return "\n".join(L) + "\n"

def change_report(sm: dict) -> str:
    require_frozen(sm)
    out = [f"# MongoDB -> SQL change report (map revision {sm['revision']}, hash {sm['content_hash'][:12]})", ""]
    for t in dependency_order(sm["tables"]):
        spec = sm["tables"][t]
        kind = ("collection" if spec["kind"] == "root" else f"array `{spec['array_path']}` of")
        out += [f"## `{t}` <- {kind} `{spec['source_collection']}` (ORM class `{class_name(t)}`)", "",
                "| Column | SQL type | Source path | Rule | Nullable | Confidence |", "|---|---|---|---|---|---|"]
        for c in sorted(spec["columns"], key=lambda x: (x != "id", x)):
            v = spec["columns"][c]
            out.append(f"| {c} | {v['sql_type']} | {v['source_path'] or '(generated)'} | {v.get('transform')} | "
                       f"{'yes' if v['nullable'] else 'no'} | {v['confidence']} |")
        for fk in spec["foreign_keys"]:
            out.append(f"\nForeign key `{fk['column']}` -> `{fk['ref_table']}.{fk['ref_column']}`")
        out.append("")
    out += ["## Access-pattern changes", "",
            "- `db.orders.find_one({...})` with embedded `items` becomes a join: `orders` -> `orders_items` (via `OrderItem.order_id`).",
            "- Embedded `address` becomes flat `address_*` columns on `customers`.",
            "- References by ObjectId become VARCHAR(24) foreign keys enforced by PostgreSQL."]
    return "\n".join(out) + "\n"
