def load_files():
    return json.loads(zlib.decompress(base64.b64decode("".join(PAYLOAD.split()))).decode("utf-8"))

def main():
    ap = argparse.ArgumentParser(description="Build the SchemaShift project and ZIP")
    ap.add_argument("--out", default=".", help="directory to create SchemaShift/ and SchemaShift.zip in")
    ap.add_argument("--force", action="store_true", help="overwrite an existing SchemaShift/ directory's files")
    ap.add_argument("--no-zip", action="store_true")
    a = ap.parse_args()
    out = pathlib.Path(a.out).resolve(); proj = out / "SchemaShift"
    if proj.exists() and not a.force:
        sys.exit(f"{proj} already exists. Re-run with --force to overwrite its files, or choose another --out.")
    files = load_files()
    files["build_schemashift.py"] = pathlib.Path(__file__).read_text(encoding="utf-8")
    manifest = {"project": "SchemaShift", "version": files.get("VERSION", "").strip(),
                "files": [{"path": p, "bytes": len(t.encode("utf-8")), "sha256": hashlib.sha256(t.encode("utf-8")).hexdigest()}
                          for p, t in sorted(files.items())]}
    files["MANIFEST.json"] = json.dumps(manifest, indent=2) + "\n"
    for rel, text in sorted(files.items()):
        dest = proj / rel; dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text, encoding="utf-8", newline="\n")
    for rel, ent in [(e["path"], e) for e in manifest["files"]]:   # verify what was written
        got = hashlib.sha256((proj / rel).read_bytes()).hexdigest()
        if got != ent["sha256"]:
            sys.exit(f"verification failed for {rel}")
    print(f"Created {proj} with {len(files)} files.")
    if not a.no_zip:
        zpath = out / "SchemaShift.zip"
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for rel in sorted(files):
                info = zipfile.ZipInfo(f"SchemaShift/{rel}", date_time=(2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED; info.external_attr = 0o644 << 16
                z.writestr(info, (proj / rel).read_bytes())
        print(f"Created {zpath} ({zpath.stat().st_size} bytes)")
    print("Next: cd SchemaShift ; read RUN_IN_VSCODE.md")

if __name__ == "__main__":
    main()
