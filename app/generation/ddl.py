"""Deterministic PostgreSQL DDL generation from a FROZEN schema map."""
from __future__ import annotations
import re
from ..schema_map.schema_map import require_frozen

_IDENT = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")
_RESERVED = {"user", "order", "group", "table", "select", "where", "from", "end", "check", "default"}
_ALLOWED_TYPES = re.compile(r"^(TEXT|BIGINT|BIGSERIAL|INTEGER|DOUBLE PRECISION|BOOLEAN|TIMESTAMPTZ|"
                            r"VARCHAR\(\d{1,4}\)|NUMERIC\(\d{1,2},\d{1,2}\))$")

class GenerationError(Exception):
    pass

def validate_identifier(name: str) -> str:
    if not _IDENT.match(name):
        raise GenerationError(f"invalid SQL identifier {name!r}")
    return name

def quote_ident(name: str) -> str:
    validate_identifier(name)
    return '"' + name.replace('"', '""') + '"'

def dependency_order(tables: dict) -> list:
    """Topological order (parents first), sorted by name for reproducibility.
    Self-references are allowed (added inline); other cycles raise GenerationError."""
    deps = {t: set() for t in tables}
    for t, spec in tables.items():
        for fk in spec["foreign_keys"]:
            if not fk["resolved"] or fk["ref_table"] not in tables:
                raise GenerationError(f"{t}.{fk['column']} has an unresolved foreign key")
            if fk["ref_table"] != t:
                deps[t].add(fk["ref_table"])
    order, done = [], set()
    remaining = set(tables)
    while remaining:
        ready = sorted(t for t in remaining if deps[t] <= done)
        if not ready:
            cycle = sorted(remaining)
            raise GenerationError("foreign key dependency cycle among tables: " + ", ".join(cycle)
                                  + " - break the cycle (e.g. nullable FK added later) and re-approve")
        order += ready
        done |= set(ready)
        remaining -= set(ready)
    return order

def generate_ddl(sm: dict, schema_name: str = "schemashift_demo") -> str:
    require_frozen(sm)
    validate_identifier(schema_name)
    tables = sm["tables"]
    lines = [f"-- Generated by SchemaShift from frozen schema map (hash {sm['content_hash'][:12]}, revision {sm['revision']})",
             "-- Do not edit by hand; regenerate from the frozen map.",
             f"CREATE SCHEMA IF NOT EXISTS {quote_ident(schema_name)};", ""]
    q = quote_ident(schema_name)
    for tname in dependency_order(tables):
        spec = tables[tname]
        cols, cons = [], []
        for cname in sorted(spec["columns"], key=lambda c: (c != "id", c)):
            col = spec["columns"][cname]
            if not _ALLOWED_TYPES.match(col["sql_type"]):
                raise GenerationError(f"disallowed SQL type {col['sql_type']!r} on {tname}.{cname}")
            null = "" if col["nullable"] or cname in spec["primary_key"] else " NOT NULL"
            cols.append(f"    {quote_ident(cname)} {col['sql_type']}{null}")
        cons.append(f"    PRIMARY KEY ({', '.join(quote_ident(c) for c in spec['primary_key'])})")
        for uq in spec.get("unique", []):
            for u in uq:
                if u not in spec["columns"]:
                    raise GenerationError(f"unique constraint on unknown column {tname}.{u}")
            cons.append(f"    UNIQUE ({', '.join(quote_ident(u) for u in uq)})")
        for fk in sorted(spec["foreign_keys"], key=lambda f: f["column"]):
            cons.append(f"    FOREIGN KEY ({quote_ident(fk['column'])}) REFERENCES "
                        f"{q}.{quote_ident(fk['ref_table'])} ({quote_ident(fk['ref_column'])})")
        lines.append(f"CREATE TABLE IF NOT EXISTS {q}.{quote_ident(tname)} (")
        lines.append(",\n".join(cols + cons))
        lines.append(");")
        for fk in sorted(spec["foreign_keys"], key=lambda f: f["column"]):
            ix = quote_ident(("ix_" + tname + "_" + fk["column"])[:63])
            lines.append(f"CREATE INDEX IF NOT EXISTS {ix} ON {q}.{quote_ident(tname)} ({quote_ident(fk['column'])});")
        lines.append("")
    return "\n".join(lines)

def generate_rollback(sm: dict, schema_name: str = "schemashift_demo") -> str:
    """Drops ONLY the tables named in the frozen map, in reverse dependency order, in the demo schema."""
    require_frozen(sm)
    q = quote_ident(schema_name)
    out = [f"-- SchemaShift rollback for schema {schema_name}: drops only the tables listed below.",
           "-- IRREVERSIBLE: data in these tables is lost. Run via scripts/rollback (requires ALLOW_DESTRUCTIVE_CLEANUP=true)."]
    for t in reversed(dependency_order(sm["tables"])):
        out.append(f"DROP TABLE IF EXISTS {q}.{quote_ident(t)};")
    return "\n".join(out) + "\n"
