import datetime as dt, unittest
from decimal import Decimal
from app.etl.transform import convert, transform_document, TransformError, leaf_paths
from sample_data.generate import FakeObjectId, generate_seed
from tests.fixtures import frozen_pipeline

class TestConvert(unittest.TestCase):
    def test_objectid_to_text(self):
        self.assertEqual(convert(FakeObjectId("ab" * 12), "VARCHAR(24)"), "ab" * 12)
    def test_objectid_too_long(self):
        with self.assertRaises(ValueError): convert("x" * 30, "VARCHAR(24)")
    def test_naive_datetime_is_utc(self):
        d = convert(dt.datetime(2024, 1, 2, 3, 4), "TIMESTAMPTZ")
        self.assertEqual(d.utcoffset(), dt.timedelta(0))
    def test_aware_datetime_kept_and_date_promoted(self):
        tz = dt.timezone(dt.timedelta(hours=5, minutes=30))
        self.assertEqual(convert(dt.datetime(2024, 1, 1, tzinfo=tz), "TIMESTAMPTZ").utcoffset(), dt.timedelta(hours=5, minutes=30))
        self.assertEqual(convert(dt.date(2024, 1, 1), "TIMESTAMPTZ").hour, 0)
    def test_iso_string_date(self):
        self.assertEqual(convert("2024-05-01T10:00:00Z", "TIMESTAMPTZ").year, 2024)
        with self.assertRaises(ValueError): convert("not a date", "TIMESTAMPTZ")
    def test_numeric_exact_and_lossy(self):
        self.assertEqual(convert(Decimal("799.00"), "NUMERIC(12,2)"), Decimal("799.00"))
        self.assertEqual(convert(9.5, "NUMERIC(12,2)"), Decimal("9.50"))
        with self.assertRaises(ValueError): convert(Decimal("1.234"), "NUMERIC(12,2)")
    def test_int_rules(self):
        self.assertEqual(convert(3.0, "BIGINT"), 3)
        with self.assertRaises(ValueError): convert(3.5, "BIGINT")
        with self.assertRaises(ValueError): convert(True, "BIGINT")
        with self.assertRaises(ValueError): convert("many", "BIGINT")
    def test_bool_strict(self):
        with self.assertRaises(ValueError): convert("yes", "BOOLEAN")

class TestTransform(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.p = frozen_pipeline(); cls.sm = cls.p.load_map(); cls.seed = generate_seed()
    def test_nested_object_flattened(self):
        rows = transform_document(self.sm, "customers", self.seed["customers"][0])["customers"][0]
        self.assertEqual(rows["address_city"], "Pune"); self.assertEqual(rows["full_name"], "Asha Patil")
    def test_null_and_absent_become_none(self):
        row = transform_document(self.sm, "customers", self.seed["customers"][0])["customers"][0]
        self.assertIsNone(row["phone"])                      # explicit null
        row = transform_document(self.sm, "customers", self.seed["customers"][1])["customers"][0]
        self.assertIsNone(row["profile_source"])             # absent optional nested object
    def test_array_expands_to_child_rows_with_position(self):
        out = transform_document(self.sm, "orders", self.seed["orders"][1])
        items = out["orders_items"]
        self.assertEqual(len(items), len(self.seed["orders"][1]["items"]))
        self.assertEqual([r["position"] for r in items], list(range(len(items))))
        self.assertTrue(all(r["order_id"] == str(self.seed["orders"][1]["_id"]) for r in items))
        self.assertNotIn("id", items[0])                     # generated by the database
    def test_optional_shipping_null_container(self):
        doc = dict(self.seed["orders"][0]); doc["shipping"] = None
        row = transform_document(self.sm, "orders", doc)["orders"][0]
        self.assertIsNone(row["shipping_method"])
    def test_unmapped_field_fails_loudly(self):
        doc = dict(self.seed["products"][0]); doc["surprise"] = 1
        with self.assertRaises(TransformError) as c: transform_document(self.sm, "products", doc)
        self.assertIn("surprise", c.exception.path)
    def test_required_missing_fails(self):
        doc = dict(self.seed["products"][0]); del doc["name"]
        with self.assertRaises(TransformError): transform_document(self.sm, "products", doc)
    def test_wrong_type_reports_document_id(self):
        doc = dict(self.seed["products"][0]); doc["stockQuantity"] = "many"
        with self.assertRaises(TransformError) as c: transform_document(self.sm, "products", doc)
        self.assertEqual(c.exception.doc_id, str(doc["_id"]))
    def test_leaf_paths(self):
        self.assertEqual(leaf_paths({"a": {"b": 1}, "c": [{"d": 2}], "e": None}), {"a.b", "c[].d", "e"})
